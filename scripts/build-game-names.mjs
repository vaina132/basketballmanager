// Builds src/data/game-names.ts: game names for real clubs, arenas, leagues and people (owner decision, 27 November 2026).
// Usage: node scripts/build-game-names.mjs <rename folder>  (reads out/CLUBS1.json, out/CLUBS2.json, out/PEOPLE.json and batches/)
import { readFileSync, writeFileSync, existsSync } from 'node:fs'

const dir = process.argv[2]
const read = (file) => JSON.parse(readFileSync(`${dir}/${file}`, 'utf8'))
/** Pack competition id -> game name. */
const COMPETITIONS = {
  'competition-688073ba-ca47-4567-85cc-fc46f595df6a': 'Euro Elite League',
  'competition-0b11c2f6-7622-433e-923b-ab57f4ce8192': 'Euro Challenge Cup',
  'competition-a0602a8e-b4d9-42de-baee-c6ddcdb5a5cb': 'Continental Basketball Cup',
  'competition-3234c794-8cc6-431b-8681-8a6c1ab4da6d': 'Ligue Élite',
  'competition-3bccebba-0d84-43a5-8f95-7f3f8b2dc563': 'Ligue Élite 2',
  'competition-3e155be6-d006-4b06-bc74-ba370b467a7d': 'Basket Süper Lig',
  'competition-9bf9167d-ef72-4bbe-acbe-2a75bbfc65d3': 'Türkiye Basket 1. Lig',
  'competition-54e81659-e9d5-412c-98ab-bc1d7991149a': 'Liga Española',
  'competition-9e17a8ab-06df-423e-9c86-9a0b66800ef5': 'Liga Española 2',
  'competition-6004e0fa-55cb-46c4-8f03-c1aaac3e6d3b': 'Hellenic Basket League',
  'competition-ac045499-adb7-4aad-8047-2e8e5e33831d': 'Deutsche Basketball Liga',
  'competition-d14c969c-700c-5b34-991a-6171d901146b': 'North American League',
  'competition-ff4b0e63-3238-42be-83de-288a0119bae6': 'Serie A Basket',
  'competition-fa524ce7-45c4-4a86-8b4e-505071f5fefa': 'Serie A2 Basket',
}
/** Next-division league name -> game name. */
const LOWER_LEAGUES = { 'Türkiye Basketbol 2. Ligi': 'Türkiye Basket 2. Lig', 'Segunda FEB': 'Liga Española 3', 'ProA': 'Deutsche Basketball Liga 2', 'Elite League': 'Hellenic Basket League 2' }

const clubs = {}, lowerClubs = {}
for (const batch of ['CLUBS1', 'CLUBS2']) {
  const out = read(`out/${batch}.json`)
  for (const record of read(`batches/${batch}.json`)) {
    const entry = out[record.id]
    if (!entry) throw new Error(`${batch}: ${record.name} has no new name`)
    if (record.kind === 'pack') clubs[record.id] = [entry.name, entry.shortName, entry.arena ?? null]
    else lowerClubs[`${record.country}|${record.name}`] = [entry.name, entry.shortName]
  }
}
const people = existsSync(`${dir}/out/PEOPLE.json`) ? read('out/PEOPLE.json') : {}
const block = (name, type, value) => `export const ${name}: Readonly<Record<string, ${type}>> = ${JSON.stringify(value, null, 1).replace(/\n\s*/g, '\n  ').replace(/\n  \}$/, '\n}')}\n`
writeFileSync('src/data/game-names.ts', `// Generated by scripts/build-game-names.mjs (owner decision, 27 November 2026). Do not edit by hand.
// The game's own names for the real clubs, arenas, leagues and people, close to the real ones but never the brand.

/** Pack competition id -> game name. */
${block('COMPETITION_NAMES', 'string', COMPETITIONS)}
/** Next-division league name -> game name. */
${block('LOWER_LEAGUE_NAMES', 'string', LOWER_LEAGUES)}
/** Pack club id -> [name, short name, arena or null]. */
${block('CLUB_NAMES', 'readonly [string, string, string | null]', clubs)}
/** "Country|real name" of a next-division club -> [name, short name]. */
${block('LOWER_CLUB_NAMES', 'readonly [string, string]', lowerClubs)}
/** A real coach's, president's or assistant's name -> game name. */
${block('PEOPLE_NAMES', 'string', people)}`)
console.log(Object.keys(clubs).length, 'clubs,', Object.keys(lowerClubs).length, 'next-division clubs,', Object.keys(people).length, 'people')
