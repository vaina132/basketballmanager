// Builds src/data/player-names.ts from name files ({ "<player id>": "<New Name>" }). Usage: node scripts/build-player-names.mjs <names.json>...
import { readFileSync, writeFileSync } from 'node:fs'

const names = {}
const seen = new Map()
const key = (s) => s.normalize('NFKD').replace(/[\u0300-\u036f]/g, '').toLowerCase().replace(/[^a-z. ]/g, '').trim()
for (const file of process.argv.slice(2)) {
  for (const [id, name] of Object.entries(JSON.parse(readFileSync(file, 'utf8')))) {
    if (!/^player-[0-9a-z-]+$/.test(id)) throw new Error(`${file}: unexpected id ${id}`)
    if (typeof name !== 'string' || !name.trim() || name.length > 40 || /[<>"\\{}]/.test(name)) throw new Error(`${file}: ${id} has an unusable name ${name}`)
    const k = key(name)
    if (seen.has(k) && seen.get(k) !== id) throw new Error(`${file}: ${name} is used twice (${seen.get(k)} and ${id})`)
    seen.set(k, id)
    names[id.slice('player-'.length)] = name.trim()
  }
}
const ids = Object.keys(names).sort()
writeFileSync('src/data/player-names.ts', `// Generated by scripts/build-player-names.mjs (owner decision, 27 November 2026). Do not edit by hand.
// Real-pack players carry a different, real-sounding name close to their own: each part replaced by a real first name
// or surname of the same culture. Key: the pack player id without "player-".

export const PLAYER_NAMES: Readonly<Record<string, string>> = {
${ids.map((id) => `  "${id}": ${JSON.stringify(names[id])},`).join('\n')}
}
`)
console.log(`${ids.length} names written`)
