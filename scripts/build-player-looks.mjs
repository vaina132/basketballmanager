// Builds src/data/player-looks.ts from look files ({ "<player id>": { "look": "<code>", "source": "..." } }).
// Usage: node scripts/build-player-looks.mjs <looks.json>...   (Node 24: imports the TypeScript codec directly.)
import { readFileSync, writeFileSync } from 'node:fs'
import { decodeLook, packLook } from '../src/ui/player-look.ts'

const looks = {}
for (const file of process.argv.slice(2)) {
  for (const [id, entry] of Object.entries(JSON.parse(readFileSync(file, 'utf8')))) {
    const look = decodeLook(entry.look)
    if (!look) throw new Error(`${file}: ${id} has an invalid look ${entry.look}`)
    if (!/^player-[0-9a-z-]+$/.test(id)) throw new Error(`${file}: unexpected id ${id}`)
    looks[id.slice('player-'.length)] = packLook(look)
  }
}
const ids = Object.keys(looks).sort()
writeFileSync('src/data/player-looks.ts', `// Generated by scripts/build-player-looks.mjs from looks read from photos and pictures found online (25 November 2026). Do not edit by hand.
// Key: the real-pack player id without "player-". Value: the packed look (see packLook in src/ui/player-look.ts).

export const PLAYER_LOOK_CODES: Readonly<Record<string, string>> = {
${ids.map((id) => `  "${id}": "${looks[id]}",`).join('\n')}
}
`)
console.log(`${ids.length} looks written`)
